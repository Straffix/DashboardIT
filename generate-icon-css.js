const fs = require('fs')
const path = require('path')

const projectRoot = path.resolve(__dirname)
const iconDir = path.join(projectRoot, 'img', 'ico')
const outputPath = path.join(projectRoot, 'styles', 'css', 'app-icons.css')

const compressSvg = svg =>
	svg
		.replace(/<\?xml[\s\S]*?\?>/gi, '')
		.replace(/<!--[\s\S]*?-->/g, '')
		.replace(/>\s+</g, '><')
		.replace(/\s{2,}/g, ' ')
		.trim()

const encodeSvgDataUrl = svg => `data:image/svg+xml,${encodeURIComponent(compressSvg(svg))}`

const buildRule = (iconName, svgContent) =>
	`.app-icon.${iconName} { --icon-url: url("${encodeSvgDataUrl(svgContent)}"); }`

const generateCss = () => {
	const iconFiles = fs
		.readdirSync(iconDir, { withFileTypes: true })
		.filter(entry => entry.isFile() && path.extname(entry.name).toLowerCase() === '.svg')
		.map(entry => entry.name)
		.sort((left, right) => left.localeCompare(right))

	const rules = iconFiles.map(fileName => {
		const filePath = path.join(iconDir, fileName)
		const iconName = path.basename(fileName, '.svg')
		const svgContent = fs.readFileSync(filePath, 'utf8')
		return buildRule(iconName, svgContent)
	})

	return [
		'/* Generated by generate-icon-css.js */',
		'/* Keeps app icons working over file:// by avoiding mask-image URLs that point to local files. */',
		...rules,
		'',
	].join('\n')
}

fs.writeFileSync(outputPath, generateCss(), 'utf8')
console.log(`Generated ${path.relative(projectRoot, outputPath)}`)
